# Extraction-time override (not upstream): every extracted HTTP call uses this
# timeout instead of the upstream literals.  A calendar lookup must fail fast so
# _expected_latest_trade_date() can fall back to the weekday estimate.
_ASTOCK_HTTP_TIMEOUT = (5, 15)

