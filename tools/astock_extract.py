"""Extract the a-stock-data functions we use from the pinned SKILL.md snapshot.

Why this exists
---------------
Upstream ``simonlin1212/a-stock-data`` is a **documentation skill**: SKILL.md is
Markdown with self-contained Python code blocks.  We do not want to copy the
whole 440 KB file into runtime code (it contains dozens of unrelated endpoints
and depends on mootdx/baostock).  Instead we extract exactly the top-level
symbols this project uses, record where each one came from, and make the result
reproducible and verifiable.

The snapshot is fixed by commit (see ``vendor/a-stock-data/VERSION``); the
upstream main branch is never consulted.  Regenerate with::

    python tools/astock_extract.py

Verify the checked-in artifact without modifying it::

    python tools/astock_extract.py --check

Exit codes: 0 = ok, 1 = mismatch / extraction error, 2 = snapshot missing.

Only one mechanical modification is applied to upstream code: HTTP timeout
literals in the extracted functions are replaced by ``_ASTOCK_HTTP_TIMEOUT`` so
a calendar lookup fails fast.  Everything else is copied verbatim at the AST
level (comments are dropped by ``ast.unparse``; provenance lives in the
generated header and manifest).
"""
