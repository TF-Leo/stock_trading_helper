def _sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def _read_version():
    values = {}
    with open(VERSION_PATH, "r", encoding="utf-8") as handle:
        for line in handle:
            key, sep, value = line.partition(":")
            if sep:
                values[key.strip()] = value.strip()
    for required in ("version", "commit", "skill_sha256"):
        if not values.get(required):
            raise SystemExit(f"VERSION 缺少字段: {required}")
    return values


def _fenced_python_blocks(text):
    """Yield the content of every ```python fenced block, in document order."""
    in_fence = False
    lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if not in_fence and stripped.startswith("```python"):
            in_fence = True
            lines = []
            continue
        if in_fence and stripped == "```":
            in_fence = False
            yield "\n".join(lines) + "\n"
            continue
        if in_fence:
            lines.append(line)


def _marked_block(text, name):
    start = text.find(f"<!-- {name}:start -->")
    end = text.find(f"<!-- {name}:end -->")
    if start < 0 or end < 0 or end <= start:
        raise SystemExit(f"上游快照缺少代码块标记: {name}")
    return list(_fenced_python_blocks(text[start:end]))


def _section_block(text, heading):
    pos = text.find(heading)
    if pos < 0:
        raise SystemExit(f"上游快照缺少章节: {heading}")
    remainder = text[pos:]
    blocks = list(_fenced_python_blocks(remainder))
    if not blocks:
        raise SystemExit(f"章节 {heading} 后没有 python 代码块")
    return [blocks[0]]


def _collect_symbols(chunks, label):
    symbols = {}
    for chunk in chunks:
        try:
            tree = ast.parse(chunk)
        except SyntaxError as exc:
            raise SystemExit(f"{label} 代码块无法解析: {exc}") from exc
        for node in tree.body:
            names = []
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                names = [node.name]
            elif isinstance(node, ast.Assign):
                names = [t.id for t in node.targets if isinstance(t, ast.Name)]
            elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                names = [node.target.id]
            for name in names:
                symbols[name] = node
    return symbols


class _TimeoutInjection(ast.NodeTransformer):
    """Replace literal HTTP timeout tuples in extracted call sites."""

    def __init__(self):
        self.count = 0

    def visit_Call(self, node):
        self.generic_visit(node)
        for keyword in node.keywords:
            if keyword.arg != "timeout":
                continue
            value = keyword.value
            if (isinstance(value, ast.Tuple) and len(value.elts) == 2
                    and all(isinstance(e, ast.Constant) and isinstance(e.value, int)
                            for e in value.elts)):
                keyword.value = ast.Name(id="_ASTOCK_HTTP_TIMEOUT", ctx=ast.Load())
                self.count += 1
        return node


def _render_node(node):
    return ast.unparse(ast.fix_missing_locations(node))


class _BaostockFallbackDisabled(ast.NodeTransformer):
    """Disable upstream's baostock fallback in §6.8 ``st_stock_list``.

    The project explicitly does not add baostock (issue #1 decision record,
    2026-11-12).  Upstream calls ``return _st_list_baostock(reason)`` when both
    Eastmoney domains are unreachable; we replace that single ``return`` with a
    ``RuntimeError`` so the failure is explicit and the status layer can fall
    back to its own short-lived cache.  Everything else is copied verbatim.
    """

    def __init__(self):
        self.count = 0

    def visit_Return(self, node):
        self.generic_visit(node)
        value = node.value
        if (isinstance(value, ast.Call)
                and isinstance(value.func, ast.Name)
                and value.func.id == "_st_list_baostock"):
            self.count += 1
            reason = ast.BinOp(
                left=ast.Constant(
                    value="东财 ST 名单不可达（%s）；baostock 兜底已禁用："
                          "本项目不引入 baostock（issue #1 决策）"),
                op=ast.Mod(),
                right=ast.Call(func=ast.Name(id="str", ctx=ast.Load()),
                               args=[ast.Name(id="exc", ctx=ast.Load())],
                               keywords=[]),
            )
            return ast.Raise(
                exc=ast.Call(func=ast.Name(id="RuntimeError", ctx=ast.Load()),
                             args=[reason], keywords=[]),
                cause=None)
        return node


# Eastmoney's session UA is set upstream by a bare module-level expression
# (``EM_SESSION.headers.update(...)``), which carries no symbol for the
# extractor to select.  Re-apply it after the generated body when the session
# is part of the selection.
POSTAMBLE = """\
# Extraction-time override (not upstream): upstream configures the Eastmoney
# session UA with a bare module-level statement that carries no named symbol.
# Re-apply it here so extracted requests do not look like a bot.
if 'EM_SESSION' in globals():
    EM_SESSION.headers.update({'User-Agent': UA})
"""


def build():
    version = _read_version()
    with open(SKILL_PATH, "r", encoding="utf-8") as handle:
        text = handle.read()
    skill_sha = _sha256_bytes(text.encode("utf-8"))
    if skill_sha != version["skill_sha256"]:
        raise SystemExit(
            f"SKILL.md 哈希与 VERSION 不一致: {skill_sha} != {version['skill_sha256']}")

    rendered = []
    selections = []
    injections = 0
    baostock_disabled = 0
    selected_names = set()
    for label, kind, needle, names in SELECTION:
        chunks = _marked_block(text, label) if kind == "marker" else _section_block(text, needle)
        symbols = _collect_symbols(chunks, label)
        for name in names:
            if name not in symbols:
                raise SystemExit(f"上游 {label} 中找不到符号: {name}")
            node = symbols[name]
            upstream_src = _render_node(node)
            injected = _TimeoutInjection()
            node = injected.visit(ast.fix_missing_locations(node))
            injections += injected.count
            disabled = _BaostockFallbackDisabled()
            node = disabled.visit(ast.fix_missing_locations(node))
            baostock_disabled += disabled.count
            generated_src = _render_node(node)
            rendered.append(generated_src)
            selected_names.add(name)
            selections.append({
                "symbol": name,
                "section": label,
                "upstream_sha256": _sha256_bytes(upstream_src.encode("utf-8")),
                "generated_sha256": _sha256_bytes(generated_src.encode("utf-8")),
                "timeout_injections": injected.count,
                "baostock_fallback_disabled": disabled.count,
            })

    if injections == 0:
        raise SystemExit(
            "没有替换任何 HTTP timeout —— 上游代码可能已变化，"
            "请检查 _official_get / _tencent_kline_call 并更新本工具")
    if "st_stock_list" in selected_names and baostock_disabled != 1:
        raise SystemExit(
            f"st_stock_list 的 baostock 兜底替换次数应为 1，实际 {baostock_disabled} —— "
            "上游代码可能已变化，请检查 _st_list_baostock 调用点")

    body = PREAMBLE.format(
        version=version["version"],
        commit=version["commit"],
        skill_sha=skill_sha,
        body_sha="__BODY_SHA__",
    ) + "\n\n".join(rendered) + "\n"
    if "EM_SESSION" in selected_names:
        body += POSTAMBLE

    body_sha = _sha256_bytes(body.encode("utf-8"))
    output = body.replace("__BODY_SHA__", body_sha)

    modifications = [
        {
            "kind": "http_timeout_override",
            "detail": "HTTP timeout literals in extracted call sites replaced "
                      "by _ASTOCK_HTTP_TIMEOUT (5, 15).",
            "injections": injections,
        },
    ]
    if baostock_disabled:
        modifications.append({
            "kind": "baostock_fallback_disabled",
            "detail": "§6.8 st_stock_list's baostock fallback return replaced by "
                      "an explicit RuntimeError; no baostock dependency is added.",
            "injections": baostock_disabled,
        })
    if "EM_SESSION" in selected_names:
        modifications.append({
            "kind": "eastmoney_session_ua",
            "detail": "Re-applied the session User-Agent that upstream sets via an "
                      "unnamed module-level statement.",
            "injections": 1,
        })

    manifest = {
        "generator": "tools/astock_extract.py",
        "upstream": {
            "repository": "https://github.com/simonlin1212/a-stock-data",
            "version": version["version"],
            "tag": version.get("tag"),
            "commit": version["commit"],
            "skill_sha256": skill_sha,
        },
        "generated_file": os.path.relpath(OUT_PATH, ROOT).replace(os.sep, "/"),
        "generated_sha256": _sha256_bytes(output.encode("utf-8")),
        "body_sha256": body_sha,
        "selections": selections,
        "modifications": modifications,
    }
    return output, manifest


def main(argv=None):
    parser = argparse.ArgumentParser(description="Extract pinned a-stock-data symbols")
    parser.add_argument("--check", action="store_true",
                        help="verify the checked-in artifact matches the snapshot")
    parser.add_argument("--stdout", action="store_true",
                        help="print generated code instead of writing it")
    args = parser.parse_args(argv)

    if not os.path.exists(SKILL_PATH):
        print(f"ERROR 固定快照不存在: {SKILL_PATH}", file=sys.stderr)
        return 2

    output, manifest = build()
    manifest_text = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"

    if args.stdout:
        sys.stdout.write(output)
        return 0

    if args.check:
        problems = []
        if not os.path.exists(OUT_PATH):
            problems.append(f"缺少生成物: {OUT_PATH}")
        else:
            with open(OUT_PATH, "r", encoding="utf-8") as handle:
                current = handle.read()
            if current != output:
                problems.append("生成物与快照不一致（请运行 python tools/astock_extract.py）")
        if not os.path.exists(MANIFEST_PATH):
            problems.append(f"缺少清单: {MANIFEST_PATH}")
        else:
            with open(MANIFEST_PATH, "r", encoding="utf-8") as handle:
                current_manifest = handle.read()
            if current_manifest != manifest_text:
                problems.append("清单元数据不一致（请运行 python tools/astock_extract.py）")
        if problems:
            for problem in problems:
                print(f"MISMATCH {problem}", file=sys.stderr)
            return 1
        print(f"OK {os.path.relpath(OUT_PATH, ROOT)} "
              f"({len(manifest['selections'])} symbols, "
              f"sha256 {manifest['generated_sha256'][:16]}…)")
        return 0

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as handle:
        handle.write(output)
    with open(MANIFEST_PATH, "w", encoding="utf-8") as handle:
        handle.write(manifest_text)
    print(f"wrote {os.path.relpath(OUT_PATH, ROOT)} "
          f"({len(manifest['selections'])} symbols, "
          f"sha256 {manifest['generated_sha256'][:16]}…)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
